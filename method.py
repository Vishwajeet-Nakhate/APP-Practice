# String methods
text = "python"
print(text.upper())      # PYTHON
print(text.capitalize()) # Python

# List methods
numbers = [3, 1, 2]
numbers.append(4)
numbers.sort()
print(numbers)

# Dictionary methods
student = {"name": "Alice", "age": 20}
print(student.keys())
print(student.values())

# Set methods
colors = {"red", "green"}
colors.add("blue")
print(colors)

# Tuple methods
marks = (80, 90, 80, 70)
print(marks.count(80))
print(marks.index(90))
